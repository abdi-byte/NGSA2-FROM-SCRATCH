"""Synthetic student study-allocation benchmark: never a real-grade predictor."""
from dataclasses import dataclass
import numpy as np

MODULES = ('Programming', 'Mathematics', 'Digital Logic', 'Databases', 'Electronics')
BASE = np.array([59., 64., 57., 68., 61.])
GAINS = np.array([17., 13., 20., 11., 16.])
RATES = np.array([0.095, 0.08, 0.11, 0.065, 0.09])
WEIGHTS = np.array([20., 20., 20., 20., 20.]) / 100.
WEEKLY_BUDGET = 30.0
MINIMUM_HOURS = 0.0
MAXIMUM_HOURS_PER_MODULE = 15.0
GRADE_FLOOR = 70.0

@dataclass(frozen=True)
class StudyPrediction:
    hours: np.ndarray
    grades: np.ndarray
    weighted_average: float
    study_hours: float
    shortfall: float

def predict(hours):
    h = np.asarray(hours, dtype=float)
    if h.shape != (len(MODULES),) or not np.all(np.isfinite(h)):
        raise ValueError('Specify five finite nonnegative study-hour allocations.')
    if np.any(h < MINIMUM_HOURS) or np.any(h > MAXIMUM_HOURS_PER_MODULE):
        raise ValueError('Study hours must lie between 0 and 15 per module.')
    grades = BASE + GAINS * (1.0 - np.exp(-RATES * h))
    return StudyPrediction(h, grades, float(WEIGHTS @ grades), float(h.sum()),
                           float(np.maximum(GRADE_FLOOR - grades, 0).sum()))

def study_objectives(hours):
    """Minimise negative mean grade, total hours and sum of shortfalls below 70%."""
    p = predict(hours)
    # Constraint: >=30 hours is discouraged without hiding an infeasible solution.
    # Feasible-budget candidates are generated by repair_study_hours in the experiment.
    return [-p.weighted_average, p.study_hours, p.shortfall]

def repair_study_hours(hours, budget=WEEKLY_BUDGET):
    """Project a nonnegative candidate into the feasible study-hour budget."""
    h = np.clip(np.asarray(hours, dtype=float), MINIMUM_HOURS, MAXIMUM_HOURS_PER_MODULE)
    total = h.sum()
    return (h * (budget / total)).tolist() if total > budget else h.tolist()

def objectives_under_budget(hours):
    """Feasible objective mapping: repair any proposal before grading it."""
    return study_objectives(repair_study_hours(hours))
